import type { Email, Mailbox } from "../types/mail";

function email(
  id: number,
  sender: string,
  address: string,
  subject: string,
  preview: string,
  fullDate: string,
  timestamp: string,
  mailbox: Mailbox,
  unread: boolean,
  starred: boolean,
  body: string[],
): Email {
  return {
    id,
    sender,
    address,
    recipients:
      mailbox === "sent" || mailbox === "drafts"
        ? ["sam@example.com"]
        : ["me@example.com"],
    subject,
    preview,
    body,
    timestamp,
    fullDate,
    mailbox,
    unread,
    starred,
    // No mail is pinned at startup, so every mail opens as a preview tab.
    pinned: false,
  };
}

